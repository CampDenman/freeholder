import { readFileSync, writeFileSync } from "node:fs";

const catalogs = Object.fromEntries(["en", "es", "fr"].map((locale) => {
  const catalog = JSON.parse(readFileSync(new URL(`../locales/${locale}.json`, import.meta.url), "utf8"));
  return [locale, Object.fromEntries(Object.entries(catalog).filter(([key]) => key.startsWith("app.")).sort(([a], [b]) => a.localeCompare(b)))];
}));
writeFileSync(new URL("../packages/mobile-app/src/messages.generated.ts", import.meta.url),
  "// Copyright (C) 2026 Tony Aly\n// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/generate-mobile-messages.mjs from locales/*.json.\n" +
  `export const appMessages = ${JSON.stringify(catalogs, null, 2)} as const;\n`);
